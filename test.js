    // Renders an emoji reliably onto a canvas by using an SVG foreignObject trick.
    // Returns a Promise that resolves with an ImageBitmap (or falls back to a
    // plain Image) so it can be drawn with ctx.drawImage().
    function emojiToImage(emoji, size) {
      return new Promise((resolve) => {
        // Draw the emoji on a small offscreen canvas first
        const oc = document.createElement('canvas');
        oc.width = size;
        oc.height = size;
        const octx = oc.getContext('2d');
        octx.clearRect(0, 0, size, size);
        // Use a system emoji font stack to maximise rendering
        octx.font = `${Math.floor(size * 0.72)}px "Apple Color Emoji", "Segoe UI Emoji", "Noto Color Emoji", sans-serif`;
        octx.textAlign = 'center';
        octx.textBaseline = 'middle';
        octx.fillText(emoji, size / 2, size / 2 + 2);

        // Convert offscreen canvas → blob → Image so the browser composites
        // the emoji colour layers correctly before we stamp it on the main canvas
        oc.toBlob((blob) => {
          if (!blob) { resolve(null); return; }
          const url = URL.createObjectURL(blob);
          const img = new Image();
          img.onload = () => { URL.revokeObjectURL(url); resolve(img); };
          img.onerror = () => { URL.revokeObjectURL(url); resolve(null); };
          img.src = url;
        }, 'image/png');
      });
    }

